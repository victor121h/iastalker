// Headless check for the Morada UI (adapted from tools/check.mjs).
// Usage: node tools/ui_check.mjs [--page demo|index] [--stub] [--shot out.png] [--wait 2500]
//        [--eval file.js] [--w 1280 --h 800] [--nohelp] [--touch] [--clear]
// - Regenerates tools/ui_demo.html from index.html (base href "../", tools/ui_stubs.js injected
//   right before js/save.js so missing modules get contract-compatible fakes).
// - --stub forces the 2D stub renderer even if js/render.js exists.
// - --nohelp marks the first-run help card as seen; --touch emulates a phone (hasTouch, isMobile).
// - --eval runs a JS file in the page (async function body) and prints its JSON result.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
const requireG = createRequire(path.join(execSync('npm root -g').toString().trim(), 'noop.js'));
const { chromium } = requireG('playwright');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : def; };
const flag = (name) => args.includes('--' + name);
const shot = opt('shot', null);
const wait = +opt('wait', '2500');
const evalFile = opt('eval', null);
const W = +opt('w', '1280'), H = +opt('h', '800');
const page0 = opt('page', 'demo');

// ---- generate the demo page from the real index.html
const index = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
let demo = '<base href="../">\n' + index.replace('<script src="js/save.js"></script>',
  (flag('stub') ? '<script>window.MORADA_FORCE_STUB_RENDER = true;</script>\n' : '') +
  '<script src="tools/ui_stubs.js"></script>\n<script src="js/save.js"></script>');
if (flag('nostubs')) demo = demo.replace('<script src="tools/ui_stubs.js"></script>\n', '');
const drop = opt('drop', null);            // e.g. --drop js/render.js (simulates a missing module)
if (drop) demo = demo.replace(`<script src="${drop}"></script>`, '');
const pre = opt('pre', null);              // a JS file run before every script (e.g. to fake window.claude)
if (pre) demo = demo.replace('<base href="../">', '<base href="../">\n<script>' + fs.readFileSync(pre, 'utf8') + '</script>');
demo = '<!-- GENERATED by tools/ui_check.mjs from index.html — do not edit -->\n' + demo;
fs.writeFileSync(path.join(ROOT, 'tools/ui_demo.html'), demo);

const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.json': 'application/json', '.svg': 'image/svg+xml' };
const server = http.createServer((req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (p === '/') p = '/index.html';
  const f = path.join(ROOT, p);
  if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); res.end('nf'); return; }
  res.writeHead(200, { 'content-type': (TYPES[path.extname(f)] || 'application/octet-stream') + '; charset=utf-8' });
  fs.createReadStream(f).pipe(res);
});
await new Promise(r => server.listen(0, '127.0.0.1', r));
const port = server.address().port;

const launchArgs = ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: launchArgs }).catch(async () => chromium.launch({ args: launchArgs }));
const ctxOpts = { viewport: { width: W, height: H } };
if (flag('touch')) Object.assign(ctxOpts, { hasTouch: true, isMobile: true, deviceScaleFactor: +opt('dpr', '1') });
const context = await browser.newContext(ctxOpts);
if (flag('nohelp')) await context.addInitScript(() => { try { localStorage.setItem('morada.prefs', JSON.stringify({ helpSeen: true })); } catch (e) {} });
if (flag('clear')) await context.addInitScript(() => { try { if (!sessionStorage.getItem('cleared')) { Object.keys(localStorage).filter(k => k.startsWith('morada:')).forEach(k => localStorage.removeItem(k)); sessionStorage.setItem('cleared', '1'); } } catch (e) {} });
const page = await context.newPage();
await page.route(/cdnjs\.cloudflare\.com\/ajax\/libs\/three\.js\/r128\/three\.min\.js/, route =>
  route.fulfill({ status: 200, contentType: 'text/javascript', body: fs.readFileSync(path.join(ROOT, 'vendor/three.min.js')) }));
await page.route(/fonts\.(googleapis|gstatic)\.com/, route => route.fulfill({ status: 200, contentType: 'text/css', body: '' }));

let pageErrors = 0;
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log(`[console.${m.type()}]`, m.text()); });
page.on('pageerror', e => { pageErrors++; console.log('[pageerror]', e.message, '\n', (e.stack || '').split('\n').slice(0, 4).join('\n')); });

const url = page0 === 'index' ? `http://127.0.0.1:${port}/index.html` : `http://127.0.0.1:${port}/tools/ui_demo.html`;
await page.goto(url, { waitUntil: 'load' });
await page.waitForTimeout(wait);
if (evalFile) {
  const body = fs.readFileSync(evalFile, 'utf8');
  try {
    const out = await page.evaluate(`(async () => { ${body} })()`);
    console.log('[eval]', JSON.stringify(out, null, 1));
  } catch (e) { pageErrors++; console.log('[eval error]', e.message); }
}
// expose page for scripted interactions: --script file.mjs exporting default async (page) => {}
const script = opt('script', null);
if (script) {
  const mod = await import(path.resolve(script));
  try { const out = await mod.default(page, { W, H }); if (out !== undefined) console.log('[script]', JSON.stringify(out, null, 1)); }
  catch (e) { pageErrors++; console.log('[script error]', e.stack || e.message); }
}
if (shot) { await page.screenshot({ path: shot }); console.log('[shot]', shot); }
await browser.close();
server.close();
console.log(pageErrors ? `FAIL: ${pageErrors} page error(s)` : 'OK: no page errors');
process.exit(pageErrors ? 1 : 0);
